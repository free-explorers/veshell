use std::path::Path;

use serde::Deserialize;

use crate::backend::Backend;
use crate::capture::window_preview::{preview_path, WindowPreview};
use crate::flutter_engine::platform_channels::method_call::MethodCall;
use crate::flutter_engine::platform_channels::method_result::MethodResult;
use crate::state::State;

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
pub(crate) struct WindowPreviewPayload {
    pub(crate) meta_window_id: String,
    pub(crate) persistent_window_id: String,
    /// `true` associates the preview with the meta window; `false` clears it
    /// for the tile that owned it.
    pub(crate) attach: bool,
}

/// Binds a persistent tile's preview file to the window it displays, or
/// clears that binding when the tile stops displaying it.
///
/// The compositor writes the file when the window goes away (see
/// `capture::window_preview`), in its cache directory:
/// `window_previews/<uuid>.png`. The path is built here from a validated uuid,
/// so the shell never names files for the compositor to write.
pub fn window_preview<BackendData: Backend + 'static>(
    method_call: MethodCall<serde_json::Value>,
    mut result: Box<dyn MethodResult<serde_json::Value>>,
    data: &mut State<BackendData>,
) {
    let payload = method_call
        .arguments()
        .cloned()
        .and_then(|args| serde_json::from_value::<WindowPreviewPayload>(args).ok());
    let Some(payload) = payload else {
        result.error(
            "invalid_arguments".to_string(),
            "window_preview expects metaWindowId, persistentWindowId and attach".to_string(),
            None,
        );
        return;
    };
    if !is_valid_window_id(&payload.persistent_window_id) {
        result.error(
            "invalid_arguments".to_string(),
            "persistentWindowId must be a uuid".to_string(),
            None,
        );
        return;
    }

    if !payload.attach {
        // Only the tile that owns the binding may clear it: a window moved to
        // another tile has already rebound it, and the old tile's clear must
        // not remove the new one.
        let owned = data
            .window_previews
            .get(&payload.meta_window_id)
            .is_some_and(|preview| preview.persistent_window_id == payload.persistent_window_id);
        if owned {
            data.window_previews.remove(&payload.meta_window_id);
        }
        result.success(None);
        return;
    }

    if !data
        .meta_window_state
        .meta_windows
        .contains_key(&payload.meta_window_id)
    {
        result.error(
            "meta_window_doesnt_exist".to_string(),
            format!("MetaWindow {} doesn't exist", payload.meta_window_id),
            None,
        );
        return;
    }

    let path = preview_path(
        Path::new(data.settings_manager.cache_folder_path()),
        &payload.persistent_window_id,
    );
    data.window_previews.insert(
        payload.meta_window_id.clone(),
        WindowPreview {
            persistent_window_id: payload.persistent_window_id,
            path,
            persisted: false,
        },
    );
    result.success(None);
}

/// A persistent tile's uuid, as generated by the shell.
fn is_valid_window_id(id: &str) -> bool {
    !id.is_empty()
        && id.len() <= 64
        && id
            .chars()
            .all(|character| character.is_ascii_alphanumeric() || character == '-')
}

#[cfg(test)]
mod tests {
    use super::is_valid_window_id;

    #[test]
    fn a_uuid_is_a_valid_preview_id() {
        assert!(is_valid_window_id("f027b283-ace1-4099-96e9-fe9f72a3bce4"));
    }

    #[test]
    fn a_path_separator_is_not_a_valid_preview_id() {
        assert!(!is_valid_window_id("../settings"));
        assert!(!is_valid_window_id("tile/2"));
        assert!(!is_valid_window_id(""));
    }
}
